"""Build Longformer embeddings and an absolute-path LLMRouter KNN config."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_DATA = HERE / "data"
DEFAULT_ARTIFACTS = HERE / "artifacts"


def _read_jsonl(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def _yaml_string(value: Path | str) -> str:
    return json.dumps(str(value), ensure_ascii=False)


def materialize_config(data_dir: Path, artifact_dir: Path) -> Path:
    """Write a portable-at-build-time config with paths LLMRouter can resolve."""
    data_dir = data_dir.resolve()
    artifact_dir = artifact_dir.resolve()
    artifact_dir.mkdir(parents=True, exist_ok=True)
    model_path = artifact_dir / "knnrouter.pkl"
    config_path = artifact_dir / "knnrouter.yaml"
    config = f"""# Generated by evaluations/llmrouter/build_artifacts.py.
# LLMRouter resolves relative data paths against its installed package, so these
# paths intentionally become absolute when artifacts are built.
data_path:
  query_data_train: {_yaml_string(data_dir / 'query_data_train.jsonl')}
  query_data_test: {_yaml_string(data_dir / 'query_data_test.jsonl')}
  query_embedding_data: {_yaml_string(artifact_dir / 'query_embeddings_longformer.pt')}
  routing_data_train: {_yaml_string(data_dir / 'routing_data_train.jsonl')}
  routing_data_test: {_yaml_string(data_dir / 'routing_data_test.jsonl')}
  llm_data: {_yaml_string(data_dir / 'llm_candidates.json')}

model_path:
  ini_model_path: ""
  save_model_path: {_yaml_string(model_path)}
  load_model_path: {_yaml_string(model_path)}

metric:
  weights:
    performance: 1
    cost: 0
    llm_judge: 0

hparam:
  n_neighbors: 11
  weights: "distance"
  algorithm: "brute"
  leaf_size: 30
  p: 2
  metric: "cosine"
  n_jobs: -1
"""
    config_path.write_text(config, encoding="utf-8")
    return config_path


def _save_embeddings(torch: object, vectors: dict[int, object], path: Path) -> None:
    """Atomically persist embeddings so an interrupted write stays recoverable."""
    temporary = path.with_suffix(f"{path.suffix}.tmp")
    torch.save(vectors, temporary)
    temporary.replace(path)


def build_embeddings(
    data_dir: Path,
    artifact_dir: Path,
    batch_size: int,
    checkpoint_every: int,
    torch_threads: int,
) -> Path:
    """Generate the exact Longformer vectors used by LLMRouter at inference."""
    try:
        import torch
        from llmrouter.utils import get_longformer_embedding
    except ImportError as exc:
        raise SystemExit(
            "LLMRouter dependencies are missing. Run `uv sync --extra llmrouter` first."
        ) from exc

    queries: list[dict] = []
    for split in ("train", "validation", "test"):
        queries.extend(_read_jsonl(data_dir / f"query_data_{split}.jsonl"))
    queries.sort(key=lambda item: int(item["embedding_id"]))
    expected_ids = list(range(len(queries)))
    actual_ids = [int(item["embedding_id"]) for item in queries]
    if actual_ids != expected_ids:
        raise ValueError("Embedding IDs must be unique and contiguous from zero")

    if batch_size < 1:
        raise ValueError("Batch size must be at least one")
    if checkpoint_every < 1:
        raise ValueError("Checkpoint interval must be at least one")
    if torch_threads < 1:
        raise ValueError("PyTorch thread count must be at least one")

    # Longformer can otherwise occupy every WSL CPU and make the editor appear
    # disconnected. Two threads give predictable resource use on small hosts.
    torch.set_num_threads(torch_threads)

    artifact_dir.mkdir(parents=True, exist_ok=True)
    output = artifact_dir / "query_embeddings_longformer.pt"
    partial = artifact_dir / "query_embeddings_longformer.partial.pt"
    vectors: dict[int, object] = (
        torch.load(partial, map_location="cpu") if partial.exists() else {}
    )
    unknown_ids = set(vectors) - set(expected_ids)
    if unknown_ids:
        raise ValueError(
            f"Checkpoint contains unknown embedding IDs: {sorted(unknown_ids)[:5]}"
        )
    if vectors:
        print(f"Resuming from checkpoint: {len(vectors)}/{len(queries)}", flush=True)

    pending = [row for row in queries if int(row["embedding_id"]) not in vectors]
    completed_since_checkpoint = 0
    try:
        for start in range(0, len(pending), batch_size):
            batch = pending[start : start + batch_size]
            embedded = get_longformer_embedding([item["query"] for item in batch])
            if len(batch) == 1:
                embedded = embedded.unsqueeze(0)
            for row, vector in zip(batch, embedded, strict=True):
                vectors[int(row["embedding_id"])] = vector.cpu()
            completed_since_checkpoint += len(batch)
            if completed_since_checkpoint >= checkpoint_every:
                _save_embeddings(torch, vectors, partial)
                completed_since_checkpoint = 0
            print(f"Embedded {len(vectors)}/{len(queries)}", flush=True)
    except BaseException:
        if completed_since_checkpoint:
            _save_embeddings(torch, vectors, partial)
        raise

    _save_embeddings(torch, vectors, output)
    partial.unlink(missing_ok=True)
    return output


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=DEFAULT_DATA)
    parser.add_argument("--artifacts", type=Path, default=DEFAULT_ARTIFACTS)
    parser.add_argument(
        "--batch-size",
        type=int,
        default=1,
        help="Queries embedded together; keep at 1 on hosts with less than 16 GiB RAM.",
    )
    parser.add_argument(
        "--checkpoint-every",
        type=int,
        default=100,
        help="Save a resumable partial artifact after this many new embeddings.",
    )
    parser.add_argument(
        "--torch-threads",
        type=int,
        default=2,
        help="CPU threads used by PyTorch; a low value keeps WSL responsive.",
    )
    parser.add_argument(
        "--config-only",
        action="store_true",
        help="Materialize absolute paths without downloading/building embeddings.",
    )
    args = parser.parse_args()
    data_dir = args.data.resolve()
    artifact_dir = args.artifacts.resolve()
    if not args.config_only:
        output = build_embeddings(
            data_dir,
            artifact_dir,
            args.batch_size,
            args.checkpoint_every,
            args.torch_threads,
        )
        print(f"Wrote embeddings: {output}")
    config = materialize_config(data_dir, artifact_dir)
    print(f"Wrote config: {config}")


if __name__ == "__main__":
    main()
